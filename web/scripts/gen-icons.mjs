#!/usr/bin/env node
// Builds src/components/ui/icons.generated.ts from the SVG icons in ../assets/icons, so <Icon>
// can inline them (no extra requests, `currentColor`, any size).
//
//   ../assets/icons/ui/home.svg          -> "home"
//   ../assets/icons/kinds/beach.svg      -> "kinds/beach"
//   ../assets/icons/kinds-badge/beach.svg -> "kinds-badge/beach"
//
// Run `npm run icons` after changing the icons; a test fails while the file is out of date.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const webRoot = path.resolve(here, "..");
const iconsRoot = path.resolve(webRoot, "..", "assets", "icons");
export const OUTPUT = path.join(webRoot, "src", "components", "ui", "icons.generated.ts");

/** Icon folders and the name prefix each gets ("" = plain name). */
export const ICON_SETS = [
  { dir: "ui", prefix: "" },
  { dir: "kinds", prefix: "kinds/" },
  { dir: "kinds-badge", prefix: "kinds-badge/" },
];

/** Parses one icon file into the fields <Icon> needs. */
export function parseIcon(svg) {
  const match = /^\s*<svg\b([^>]*)>([\s\S]*)<\/svg>\s*$/.exec(svg);
  if (!match) throw new Error("gen-icons: not a single <svg> element");
  const [, attrs, body] = match;
  const attr = (name) => new RegExp(`\\s${name}="([^"]*)"`).exec(attrs)?.[1] ?? null;
  const viewBox = attr("viewBox");
  if (!viewBox) throw new Error("gen-icons: <svg> has no viewBox");
  return {
    viewBox,
    // Line icons draw with the current text colour; badges and game icons carry their own fills.
    stroke: attr("stroke") === "currentColor",
    title: attr("aria-label") ?? "",
    body: body.trim(),
  };
}

export function collectIcons(root = iconsRoot) {
  const icons = {};
  for (const { dir, prefix } of ICON_SETS) {
    const folder = path.join(root, dir);
    const files = fs
      .readdirSync(folder)
      .filter((f) => f.endsWith(".svg"))
      .sort();
    for (const file of files) {
      const name = prefix + file.replace(/\.svg$/, "");
      icons[name] = parseIcon(fs.readFileSync(path.join(folder, file), "utf8"));
    }
  }
  return icons;
}

export function buildModule(icons = collectIcons()) {
  const lines = [
    "// Generated by scripts/gen-icons.mjs from ../assets/icons — do not edit. Run `npm run icons`.",
    "",
    "export type IconData = { viewBox: string; stroke: boolean; title: string; body: string };",
    "",
    "export const ICONS = {",
  ];
  for (const [name, icon] of Object.entries(icons)) {
    lines.push(`  ${JSON.stringify(name)}: ${JSON.stringify(icon)},`);
  }
  lines.push("} as const satisfies Record<string, IconData>;", "");
  lines.push("export type IconName = keyof typeof ICONS;", "");
  return lines.join("\n");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = buildModule();
  fs.writeFileSync(OUTPUT, out);
  console.log(`gen-icons: wrote ${path.relative(webRoot, OUTPUT)}`);
}
